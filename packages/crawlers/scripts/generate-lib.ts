/** Pure helpers for the `crawler:generate` task. */
import { DEFAULT_MARKER_KEY } from "./sanitize.js";

export const USAGE = `Usage: mise run crawler:generate <name> <url> [--marker-key <key>]

  name          kebab-case crawler id, e.g. my-bank
  url           http(s) URL where recording starts
  --marker-key  key that toggles manual (pause) mode (default: ${DEFAULT_MARKER_KEY})`;

export interface GenerateArgs {
  name: string;
  url: string;
  markerKey: string;
}

export type ParseResult =
  | { ok: true; args: GenerateArgs }
  | { ok: false; error: string };

const KEBAB_CASE = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;

export function parseArgs(argv: string[]): ParseResult {
  const positional: string[] = [];
  let markerKey = DEFAULT_MARKER_KEY;
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i] as string;
    if (arg === "--marker-key") {
      const value = argv[++i];
      if (!value) {
        return { ok: false, error: "--marker-key requires a value." };
      }
      markerKey = value;
    } else if (arg.startsWith("--marker-key=")) {
      markerKey = arg.slice("--marker-key=".length);
      if (!markerKey) {
        return { ok: false, error: "--marker-key requires a value." };
      }
    } else if (arg.startsWith("--")) {
      return { ok: false, error: `Unknown option: ${arg}` };
    } else {
      positional.push(arg);
    }
  }

  const [name, url, ...extra] = positional;
  if (!name || !url) {
    return { ok: false, error: "Both <name> and <url> are required." };
  }
  if (extra.length > 0) {
    return { ok: false, error: `Unexpected argument: ${extra[0]}` };
  }
  if (!KEBAB_CASE.test(name)) {
    return {
      ok: false,
      error: `Invalid name "${name}": must be kebab-case (e.g. my-bank).`,
    };
  }
  let parsed: URL;
  try {
    parsed = new URL(url);
  } catch {
    return { ok: false, error: `Invalid URL "${url}".` };
  }
  if (parsed.protocol !== "http:" && parsed.protocol !== "https:") {
    return { ok: false, error: `URL must be http(s): "${url}".` };
  }
  return { ok: true, args: { name, url, markerKey } };
}

export function toCamelCase(name: string): string {
  return name.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

export function toDisplayName(name: string): string {
  return name
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

export function exportName(name: string): string {
  return `${toCamelCase(name)}Crawler`;
}

export function renderBanner(markerKey: string): string {
  const width = 70;
  const bar = "#".repeat(width);
  const line = (text = "") => `##  ${text.padEnd(width - 6)}  ##`;
  const rows = [
    bar,
    line(),
    line(`PRESS  ${markerKey}  TO TOGGLE MANUAL (PAUSE) MODE ON / OFF`),
    line(),
    line(`1st press of ${markerKey}: manual mode ON  (stop recording)`),
    line(`2nd press of ${markerKey}: manual mode OFF (resume recording)`),
    line(),
    line("Everything between the two presses (e.g. logging in) is NOT"),
    line("recorded; the crawler will pause there for you to act by hand."),
    line(),
    line("IMPORTANT: click into a field or button BEFORE pressing"),
    line(`${markerKey}. With nothing focused, codegen drops the key press.`),
    line(),
    line("To finish: close the browser window."),
    ...(process.platform === "darwin" && /^F\d+$/.test(markerKey)
      ? [line(`macOS: hold fn while pressing ${markerKey} for function keys.`)]
      : []),
    line(),
    bar,
  ];
  return rows.join("\n");
}

export interface RenderOptions {
  name: string;
  url: string;
  steps: string[];
}

function indent(text: string, spaces: number): string {
  const pad = " ".repeat(spaces);
  return text
    .split("\n")
    .map((line) => (line ? pad + line : line))
    .join("\n");
}

export function renderCrawler({ name, url, steps }: RenderOptions): string {
  const body = steps.map((step) => indent(step, 6)).join("\n");
  const display = toDisplayName(name);
  return `import type { Crawler } from "crawler-core";
import { chromium } from "playwright";

/**
 * Generated by \`mise run crawler:generate\`. Review before committing: manual
 * sections were replaced by \`page.pause()\` so credentials are entered by hand.
 */
export const ${exportName(name)}: Crawler = {
  id: ${JSON.stringify(name)},
  name: ${JSON.stringify(display)},
  description: ${JSON.stringify(`Crawler for ${display} (${new URL(url).host}).`)},
  // biome-ignore lint/correctness/useYield: transaction extraction is still a TODO
  async *run() {
    // Headed so that page.pause() lets the user act manually.
    const browser = await chromium.launch({ headless: false });
    try {
      const context = await browser.newContext();
      const page = await context.newPage();
${body}

      // TODO: extract transactions from the page and yield them.
    } finally {
      await browser.close();
    }
  },
};
`;
}

/** Idempotently registers a generated crawler in the index source. */
export function registerInIndex(source: string, name: string): string {
  const symbol = exportName(name);
  const importLine = `import { ${symbol} } from "./${name}.js";`;
  if (source.includes(importLine)) {
    return source;
  }
  const lines = source.split("\n");

  let lastImport = -1;
  lines.forEach((line, i) => {
    if (line.startsWith("import ")) lastImport = i;
  });
  lines.splice(lastImport + 1, 0, importLine);

  let lastRegister = -1;
  lines.forEach((line, i) => {
    if (line.startsWith("registerCrawler(")) lastRegister = i;
  });
  lines.splice(lastRegister + 1, 0, `registerCrawler(${symbol});`);

  const exportIndex = lines.findIndex((line) => line.startsWith("export {"));
  if (exportIndex !== -1) {
    lines[exportIndex] = (lines[exportIndex] as string).replace(
      /\s*};?$/,
      `, ${symbol} };`,
    );
  }
  return lines.join("\n");
}
